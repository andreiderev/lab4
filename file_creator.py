# Модуль для створення початкового текстового файлу (частина а)

def get_initial_lines():
    # Формування списку символьних рядків різної довжини з пробілами та розділовими знаками
    return [
        "Осінь прийшла швидко, і алеї парку вкрилися жовтим листям.",
        "Апельсин, яблуко, груша — улюблені фрукти!",
        "Екран монітора світився яскраво; інформація оновлювалась щосекунди.",
        "Їжак обережно йшов уздовж стежки: навколо була тиша.",
        "Університет, освіта, ідеї та успіх."
    ]


def create_source_file(filename):
    # Створення файлу TF16_1 та запис початкових рядків із обробкою помилок
    lines = get_initial_lines()
    try:
        with open(filename, "w", encoding="utf-8") as file:
            for line in lines:
                file.write(line + "\n")
        print(f"Файл '{filename}' успішно створено.")
        return True
    except OSError as error:
        print(f"Помилка відкриття або запису файлу '{filename}': {error}")
        return False